let currentLang = localStorage.getItem('cnpenas:lang') || 'es';

// Traduce una clave del diccionario; {variable} dentro del texto se sustituye por vars.variable
function t(key, vars){
  let str = (I18N[currentLang] && I18N[currentLang][key]) || I18N.es[key] || key;
  if(vars){ Object.keys(vars).forEach(k => { str = str.split('{' + k + '}').join(vars[k]); }); }
  return str;
}

// Traduce todo lo marcado con data-i18n / data-i18n-attr, y refresca el estado
// visual del selector de idioma (sidebar de escritorio + botón de la barra móvil)
function applyI18n(){
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.getAttribute('data-i18n-attr').split(',').forEach(pair => {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    });
  });
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
  const mobileToggle = document.getElementById('lang-toggle-mobile');
  if(mobileToggle) mobileToggle.setAttribute('data-lang', currentLang);
  document.documentElement.lang = currentLang;
}

// Cambia el idioma activo, lo guarda para la próxima visita y refresca tanto los
// textos fijos como los que genera JS dinámicamente en la pantalla de Inicio (las
// demás pantallas se irán sumando aquí a medida que se traduzcan).
function setLang(lang){
  if(lang !== 'es' && lang !== 'ca') return;
  currentLang = lang;
  localStorage.setItem('cnpenas:lang', lang);
  applyI18n();
  // Las secciones ya migradas a Svelte se repintan solas al recibir este evento.
  window.dispatchEvent(new CustomEvent('app:langchange', { detail: lang }));
  if(typeof renderNextMatchBanner === 'function') renderNextMatchBanner();
  if(typeof renderWellnessReminderBanner === 'function') renderWellnessReminderBanner();
  if(typeof renderInicioFinesBanner === 'function') renderInicioFinesBanner();
  if(typeof renderInicioTercerBanner === 'function') renderInicioTercerBanner();
  if(typeof checkInicioSharedLineupBanner === 'function') checkInicioSharedLineupBanner();
  if(typeof renderProfile === 'function' && typeof currentUserId !== 'undefined' && currentUserId) renderProfile();
  if(typeof renderEventList === 'function') renderEventList();
  if(typeof renderEventDetail === 'function' && typeof currentEventId !== 'undefined' && currentEventId) renderEventDetail();
  if(typeof renderCalendarGrid === 'function') renderCalendarGrid();
  if(typeof renderPartidosList === 'function') renderPartidosList();
  if(typeof renderMyFinesSummary === 'function') renderMyFinesSummary();
  if(typeof renderFinesTable === 'function') renderFinesTable();
  if(document.getElementById('fines-history-modal') && document.getElementById('fines-history-modal').classList.contains('active') && typeof renderFinesHistory === 'function') renderFinesHistory();
  if(typeof renderThirdTime === 'function') renderThirdTime();
  if(typeof renderThirdTimeFood === 'function') renderThirdTimeFood();
  if(typeof renderMatchReport === 'function' && typeof currentPartidoId !== 'undefined' && currentPartidoId) renderMatchReport(currentPartidoId);
  if(typeof renderPlantillaTable === 'function' && typeof plantillaData !== 'undefined' && plantillaData.length) renderPlantillaTable();
  if(typeof plantillaActiveTab !== 'undefined' && plantillaActiveTab === 'estadisticas' && typeof loadPlantillaStats === 'function') loadPlantillaStats();
  if(document.getElementById('comment-modal') && document.getElementById('comment-modal').classList.contains('active') && typeof commentModalCtx !== 'undefined' && commentModalCtx){
    const evForComment = attEvents.find(e => e.id === commentModalCtx.eventId);
    if(evForComment) document.getElementById('comment-modal-sub').textContent = `${evForComment.label} · ${eventWhenDisplay(evForComment)}`;
  }
}

function toggleLang(){
  setLang(currentLang === 'es' ? 'ca' : 'es');
}
